// Round-13 fixes (round-4 audit).
require('./profile-guard'); const __G = require('path').join(__dirname, '..').replace(/\\/g, '/') + '/'; // the setup under test
const path = require('path'), fs = require('fs'), os = require('os'), { spawnSync } = require('child_process');
const L = require(__G + 'lib.js');
const gate = (ev, i) => spawnSync(process.execPath, [__G + 'gate.js', ev], { input: JSON.stringify(i), encoding: 'utf8' }).stdout;
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m);
const wait = ms => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
const P = path.join(os.homedir(), 'gpt-final'); fs.rmSync(P, { recursive: true, force: true }); fs.mkdirSync(P);
const SID = 'r13-' + Date.now(), b = { cwd: P, session_id: SID };
const git = (...a) => spawnSync('git', a, { cwd: P, encoding: 'utf8' });
const f = n => path.join(P, n);
const prompt = (text = 'go') => { wait(30); gate('prompt', { ...b, prompt: text }); wait(30); };
const rec = n => { const s = L.readState(P); return Object.entries(s.changes).filter(([k]) => k.toLowerCase() === f(n).toLowerCase()); };
const K = require('./bridge-kit').at(P);
const mr = K.review.markReviewed;
const ack = () => mr('claude-final', Date.now(), null, L.gitDeleted(P));
const edit = (file, from, to, id) => {
  const ev = { ...b, tool_use_id: id, tool_name: 'Edit', tool_input: { file_path: file, old_string: from, new_string: to } };
  gate('pre-edit', ev); fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace(from, to)); gate('post-edit', ev);
};
git('init', '-q'); git('config', 'user.email', 't@t'); git('config', 'user.name', 't');
fs.writeFileSync(f('x.js'), Array.from({ length: 30 }, (_, i) => `line${i}`).join('\n') + '\n');
fs.writeFileSync(f('Case.js'), 'a\nb\nc\n');
git('add', '-A'); git('commit', '-qm', 'init'); wait(1100);
gate('session', b); prompt();

// H1. Edit (1 line) -> shell rewrites 20 lines -> Edit (1 line): the shell work counts
edit(f('x.js'), 'line0', 'LINE0', 'e1');
fs.writeFileSync(f('x.js'), fs.readFileSync(f('x.js'), 'utf8').replace(/line(1\d|[1-9])\b/g, 'shell$1'));
edit(f('x.js'), 'line25', 'LINE25', 'e2');
const cx = rec('x.js')[0][1];
ok(cx.lines >= 5 && cx.shellTouched && /x\.js/.test(gate('stop', b)), 'shell change between two small Edits makes it a full review');

// H6. the same file edited under a different capitalization: one record, original baseline kept
git('add', '-A'); git('commit', '-qm', 'x'); ack(); prompt();
edit(f('Case.js'), 'a', 'A', 'c1');
edit(f('case.js').replace(/^[a-z]/i, d => d === d.toUpperCase() ? d.toLowerCase() : d.toUpperCase()), 'b', 'B', 'c2');
const recs = rec('Case.js'), base = L.baselineOf(P, f('Case.js'));
ok(recs.length === 1 && recs[0][1].lines === 2 && base && fs.readFileSync(base, 'utf8') === 'a\nb\nc\n', 'case-different path: one record, pre-edit baseline kept');

// H4. turn ends with a background writer still running; it changes a file; then a new user prompt
git('add', '-A'); git('commit', '-qm', 'c'); ack(); prompt();
gate('post-bash', { ...b, tool_use_id: 'bg', tool_input: { command: 'node gen.js', run_in_background: true } });
gate('stop', b); // ends the turn
wait(30); fs.writeFileSync(f('gen.js'), 'generated by the background job\n');
prompt();
ok(rec('gen.js').length && rec('gen.js')[0][1].at > L.reviewedAtFor(L.readState(P), rec('gen.js')[0][1]), "background writer's change after the Stop is kept at the next prompt");

// H7. plan review recorded for the user turn survives a continuation window
git('add', '-A'); git('commit', '-qm', 'g'); ack(); prompt();
const U = L.readState(P).userTurnAt;
gate('stop', b);
prompt('<task-notification><task-id>p</task-id></task-notification>');
L.updateState(P, s => { s.planReviewedAt = Date.now(); s.planReviewedTurn = U; });
const pp = gate('pre-plan', { ...b, tool_input: {} });
ok(L.readState(P).turnStartedAt !== U && !/deny/.test(pp), 'plan reviewed in this user turn still accepted after a continuation window');

// G2. edits after the freeze: the reviewed copy becomes the baseline; an older review can't overwrite it
const G = f('g2.js'); fs.writeFileSync(G, 'v3\n');
const snapB = f('snapB.js'); fs.writeFileSync(snapB, 'v2\n'); const snapOld = f('snapA.js'); fs.writeFileSync(snapOld, 'v1\n');
L.updateState(P, s => { s.changes[G] = { lines: 5, at: Date.now() + 1000 }; });
mr('gpt', Date.now(), [G], [], { verdict: 'NO_ISSUES', log: f('rB.md'), snaps: [{ abs: G, snap: snapB }], findingFiles: new Set() });
const cg = L.readState(P).changes[G];
ok(fs.readFileSync(L.baselineOf(P, G), 'utf8') === 'v2\n' && cg.basePre && cg.at > L.reviewedAtFor(L.readState(P), cg), 'reviewed copy becomes the baseline; the newer edit stays pending');
mr('gpt', Date.now() - 60000, [G], [], { verdict: 'NO_ISSUES', log: f('rA.md'), snaps: [{ abs: G, snap: snapOld }], findingFiles: new Set() });
ok(fs.readFileSync(L.baselineOf(P, G), 'utf8') === 'v2\n', 'an older review finishing later does not overwrite the baseline');

// G1. a PARTIAL write result is shown but not staged
const SD = f('stage'); fs.mkdirSync(path.join(SD, 'work'), { recursive: true }); fs.writeFileSync(path.join(SD, 'work', 'doc.md'), 'reviewed\n');
fs.mkdirSync(path.join(SD, 'prev')); fs.writeFileSync(path.join(SD, 'prev', 'doc.md'), 'reviewed\n');
let status = 'PARTIAL';
K.codex.ask = async o => { o.before(); fs.writeFileSync(path.join(o.cwd, 'doc.md'), 'half\n'); return { ok: true, text: `STATUS: ${status}\n- did half`, log: 'l', secs: 1 }; };
K.codex.markUnavailable = () => {}; K.codex.finish = () => { throw new Error('FIN'); };
const realExit = process.exit; process.exit = () => { throw new Error('EXIT'); };
const rw = K.write.runWrite;
const log0 = console.log; console.log = () => {};
(async () => {
  try { await rw(SD, { id: 'x', round: 2, entries: [] }, path.join(SD, 'prev')); } catch {}
  const partialKept = fs.readFileSync(path.join(SD, 'work', 'doc.md'), 'utf8') === 'reviewed\n';
  status = 'DONE';
  try { await rw(SD, { id: 'x', round: 2, entries: [] }, path.join(SD, 'prev')); } catch {}
  console.log = log0; process.exit = realExit;
  ok(partialKept && fs.readFileSync(path.join(SD, 'work', 'doc.md'), 'utf8') === 'half\n', 'PARTIAL keeps the previous staged version; DONE stages the result');

  // G3. two Claude sessions can't operate the desktop at the same time
  const g0 = L.readState(L.HOME), keep = { claudeCuUntil: g0.claudeCuUntil, claudeCuSession: g0.claudeCuSession, claudeCuLastUse: g0.claudeCuLastUse };
  L.updateState(L.HOME, g => { g.claudeCuUntil = Date.now() + 60000; delete g.claudeCuSession; delete g.claudeCuLastUse; });
  const a = gate('pre-computer', { cwd: P, session_id: 'cuA', tool_name: 'mcp__computer-use__screenshot' });
  const bb = gate('pre-computer', { cwd: P, session_id: 'cuB', tool_name: 'mcp__computer-use__screenshot' });
  const a2 = gate('pre-computer', { cwd: P, session_id: 'cuA', tool_name: 'mcp__computer-use__screenshot' });
  L.updateState(L.HOME, g => { for (const [k2, v] of Object.entries(keep)) { if (v === undefined) delete g[k2]; else g[k2] = v; } });
  ok(!/deny/.test(a) && /Another Claude session/.test(bb) && !/deny/.test(a2), 'second Claude session is held off while the first operates the desktop');

  // H3. a shell edit of this setup's own files (agents) from another project is tracked
  const AG = path.join(os.homedir(), '.claude', 'agents', 'zz-test-agent.md');
  fs.mkdirSync(path.dirname(AG), { recursive: true });
  fs.writeFileSync(AG, 'name: t\n');
  gate('pre-bash', { ...b, tool_use_id: 'ga' }); fs.writeFileSync(AG, 'name: t\ntools: Bash\n'); gate('post-bash', { ...b, tool_use_id: 'ga' });
  const cAG = L.readState(P).changes[AG];
  fs.rmSync(AG, { force: true });
  ok(cAG && cAG.at > L.reviewedAtFor(L.readState(P), cAG), "shell edit of the setup's own agent file is pending");

  fs.rmSync(P, { recursive: true, force: true });
  L.updateState(L.HOME, g => { if (g.sessionRoots) delete g.sessionRoots[SID]; });
})();
